def predict_video(video_path, model):
    import cv2
    from PIL import Image
    from torchvision import transforms
    from facenet_pytorch import MTCNN
    import numpy as np

    mtcnn = MTCNN(keep_all=False, device=DEVICE)

    transform = transforms.Compose([
        transforms.Resize((299, 299)),
        transforms.ToTensor(),
        transforms.Normalize([0.5, 0.5, 0.5], [0.5, 0.5, 0.5]),
    ])

    def extract_face_mtcnn(frame):
       # convert BGR to RGB
        img = Image.fromarray(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
        boxes, _ = mtcnn.detect(img)

        if boxes is None:
            return None

        x1, y1, x2, y2 = [int(b) for b in boxes[0]]
        w = x2 - x1
        h = y2 - y1
        # add margin around the face box
        margin = int(0.2 * max(w, h))

        x1 = max(0, x1 - margin)
        y1 = max(0, y1 - margin)
        x2 = min(img.width,  x2 + margin)
        y2 = min(img.height, y2 + margin)

        return img.crop((x1, y1, x2, y2))

    # افتح الفيديو
    cap = cv2.VideoCapture(video_path)

    if not cap.isOpened():
        print("ERROR: Could not open video")
        return None, None

    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    fps          = cap.get(cv2.CAP_PROP_FPS)
    duration     = total_frames / fps if fps > 0 else 0

    print(f"Video Info: {total_frames} frames | {fps:.1f} FPS | {duration:.1f} seconds")

    fake_probs  = []
    frame_idx   = 0
    sample_rate = 3 # process every 3rd frame

    model.eval()
    with torch.no_grad():
        while True:
            ret, frame = cap.read()
            if not ret:
                break

            if frame_idx % sample_rate == 0:
                face = extract_face_mtcnn(frame)
                if face is not None:
                    tensor    = transform(face).unsqueeze(0).to(DEVICE)
                    output    = model(tensor)
                    probs     = torch.softmax(output, dim=1)
                    fake_prob = probs[0][0].item()
                    fake_probs.append(fake_prob)

            frame_idx += 1

    cap.release()

    if not fake_probs:
        print("No faces detected in video.")
        return None, None

    avg_fake_prob = np.median(fake_probs)


